static PT: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
static EN: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();

fn table(lang: Language) -> &'static HashMap<&'static str, &'static str> {
    match lang {
        Language::PtBr => PT.get_or_init(|| ENTRIES.iter().map(|(k, pt, _)| (*k, *pt)).collect()),
        Language::En => EN.get_or_init(|| ENTRIES.iter().map(|(k, _, en)| (*k, *en)).collect()),
    }
}

/// Translator for the active language.
#[derive(Debug, Clone, Copy)]
pub struct Tr {
    pub lang: Language,
}

impl Tr {
    pub fn new(lang: Language) -> Self {
        Self { lang }
    }

    /// Translates `key`; unknown keys are returned unchanged.
    pub fn t(&self, key: &'static str) -> &'static str {
        table(self.lang).get(key).copied().unwrap_or(key)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_unique() {
        let mut seen = std::collections::HashSet::new();
        for (k, _, _) in ENTRIES {
            assert!(seen.insert(*k), "duplicate key {k}");
        }
    }

    #[test]
    fn translates_both_languages() {
        assert_eq!(Tr::new(Language::PtBr).t("mute"), "Mudo");
        assert_eq!(Tr::new(Language::En).t("mute"), "Mute");
        assert_eq!(Tr::new(Language::En).t("unknown_key"), "unknown_key");
    }

    #[test]
    fn stage_and_preset_keys_exist() {
        for k in novamix_dsp::params::StageKind::DEFAULT_ORDER {
            assert_ne!(Tr::new(Language::PtBr).t(k.key()), k.key(), "{}", k.key());
        }
        for p in novamix_dsp::params::VoicePreset::ALL {
            assert_ne!(Tr::new(Language::PtBr).t(p.key()), p.key());
        }
        for a in novamix_config::HotkeyAction::ALL {
            assert_ne!(Tr::new(Language::PtBr).t(a.key()), a.key());
        }
    }
}
